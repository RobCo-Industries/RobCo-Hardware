#!/usr/bin/env python3
"""Write the header pin table of a board spec from its `pins.yaml`.

    gen_pin_table.py PINS_YAML DOC [--check]

The table goes between two marker lines in DOC:

    <!-- pin-table:start -->
    <!-- pin-table:end -->

Without `--check` the script rewrites DOC. With `--check` it changes nothing
and exits 1 when the table in DOC differs from the generated one.

Exit codes: 0 equal or written, 1 differs (with --check), 2 bad input.

Runs on Python 3.9 or later, with the standard library only.
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import List, Optional

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from check_pins import InputError, parse_pins_yaml  # noqa: E402

START = "<!-- pin-table:start -->"
END = "<!-- pin-table:end -->"
NOTE = "<!-- Generated by tools/gen_pin_table.py from pins.yaml. Edit pins.yaml, not this table. -->"


def _cell(v: object) -> str:
    return str(v).replace("|", "\\|")


def table(pins_text: str) -> str:
    """Return the Markdown table for the pins in a pins.yaml text."""
    data = parse_pins_yaml(pins_text)
    if "pins" not in data:
        raise InputError("pins.yaml has no 'pins' list")
    rows = [
        "| Pin | Pi function | Net | Software use (source) | This board connects | Status |",
        "|---|---|---|---|---|---|",
    ]
    for p in sorted(data["pins"], key=lambda e: int(e["pin"])):
        use = str(p.get("use", ""))
        src = str(p.get("source", ""))
        if use in ("power", "ground"):
            sw = use.capitalize()
        else:
            sw = f"{use} ({src})" if src else use
        net = str(p.get("net", ""))
        net = "not connected" if net == "NC" else f"`{net}`"
        cells = [p["pin"], p.get("function", p.get("name", "")), net, sw,
                 p.get("connects", ""), p.get("status", "")]
        rows.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return "\n".join(rows) + "\n"


def splice(doc: str, body: str) -> str:
    """Return doc with the text between the markers replaced by body."""
    if doc.count(START) != 1 or doc.count(END) != 1:
        raise InputError(f"the document needs exactly one '{START}' and one '{END}' line")
    head, rest = doc.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{NOTE}\n\n{body}\n{END}{tail}"


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("pins", help="the board's spec/pins.yaml")
    ap.add_argument("doc", help="the Markdown file with the table markers")
    ap.add_argument("--check", action="store_true", help="only compare, exit 1 on a difference")
    args = ap.parse_args(argv)
    try:
        with open(args.pins, encoding="utf-8") as fh:
            body = table(fh.read())
        with open(args.doc, encoding="utf-8") as fh:
            doc = fh.read()
        new = splice(doc, body)
    except (OSError, InputError, KeyError, ValueError) as exc:
        print(f"gen_pin_table: error: {exc}", file=sys.stderr)
        return 2
    if args.check:
        if new != doc:
            print(f"gen_pin_table: the pin table in {args.doc} differs from {args.pins}: "
                  f"run tools/gen_pin_table.py {args.pins} {args.doc}", file=sys.stderr)
            return 1
        print(f"gen_pin_table: the pin table in {args.doc} matches {args.pins}")
        return 0
    if new != doc:
        with open(args.doc, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
