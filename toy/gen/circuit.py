"""Toy board schematic: a 3-pin header, a resistor and an LED.

The signal on J1 pin 3 drives the LED through R1. Pin 1 brings +5V and pin 2
brings GND. The toy exists to prove the toolchain. It is not a real board.

Usage: python3 toy/gen/circuit.py [output folder]
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))

from common import g  # noqa: E402
from project import write_project  # noqa: E402
from sch import Schematic  # noqa: E402

PROJECT = "toy"

FOOTPRINTS = {
    "J1": "Connector_PinHeader_2.54mm:PinHeader_1x03_P2.54mm_Vertical",
    "R1": "Resistor_SMD:R_0805_2012Metric",
    "D1": "LED_SMD:LED_0805_2012Metric",
}

# Footprint libraries the board uses for parts that are not in the schematic.
BOARD_ONLY_LIBS = ["MountingHole"]


def build() -> Schematic:
    s = Schematic(
        PROJECT,
        title="Toy board for the toolchain test",
        date="2026-11-23",
        rev="0.1",
        comments=[
            "Proposal. Not built, not validated on hardware.",
            "Generated by toy/gen/circuit.py. Do not edit by hand.",
        ],
    )

    # Header on the left, its pins facing left.
    j1 = s.symbol(
        "Connector_Generic:Conn_01x03", "J1", "Toy header", (g(60), g(64)),
        footprint=FOOTPRINTS["J1"], ref_at=(g(-2), g(-4)), value_at=(g(-2), g(5)),
        description="3-pin header: +5V, GND, signal",
    )
    # GND leaves pin 2 to the far left and drops below the SIG label.
    s.power(j1, "1", "+5V", stub=g(3))
    s.power(j1, "2", "GND", stub=g(10), then=[(0, g(5))])
    s.label(j1, "3", "SIG", stub=g(3))

    # Resistor, laid flat, signal flows left to right.
    r1 = s.symbol(
        "Device:R", "R1", "1k", (g(80), g(64)), rot=90,
        footprint=FOOTPRINTS["R1"], ref_at=(g(-1), g(-3)), value_at=(g(-1), g(3)),
        description="LED current limit, about 1.5 mA from a 3.3 V GPIO",
    )
    s.label(r1, "1", "SIG", stub=g(3))
    s.label(r1, "2", "LED_A", stub=g(3))

    # LED, anode on the left.
    d1 = s.symbol(
        "Device:LED", "D1", "Red", (g(106), g(64)), rot=180,
        footprint=FOOTPRINTS["D1"], ref_at=(g(-1), g(-3)), value_at=(g(-1), g(3)),
        description="Indicator LED",
    )
    s.label(d1, "2", "LED_A", stub=g(3))
    s.power(d1, "1", "GND", stub=g(3))

    # The header feeds both rails.
    s.power_flag("+5V", (g(60), g(84)))
    s.power_flag("GND", (g(72), g(88)))

    s.text("Toolchain test only. J1 pin 3 drives D1 through R1.", (g(48), g(98)))
    return s


def main() -> None:
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "kicad")
    s = build()
    s.write(os.path.join(out, f"{PROJECT}.kicad_sch"))
    fp_libs = [fp.split(":", 1)[0] for fp in FOOTPRINTS.values()] + BOARD_ONLY_LIBS
    write_project(out, PROJECT, s.stock_libs(), fp_libs)


if __name__ == "__main__":
    main()
