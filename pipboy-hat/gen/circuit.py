"""Pip-Boy HAT: the schematic generator.

The root sheet holds one sheet symbol per block. Each block is drawn by a
module in gen/sheets/. Spec: pipboy-hat/spec/SPEC.md.

Usage: python3 pipboy-hat/gen/circuit.py [output folder]
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
sys.path.insert(0, HERE)

from common import g  # noqa: E402
from project import write_project  # noqa: E402
from sch import Hierarchy, Schematic  # noqa: E402

from sheets import audio, clock, display, holotape, inputs, pi_header, power, serial  # noqa: E402

PROJECT = "pipboy-hat"
BOARD = "Pip-Boy HAT"

# (sheet name, file, paper, draw function, root box position, note), in page order.
SHEETS = [
    ("Power input", "power.kicad_sch", "A4", power.draw, (g(20), g(52)),
     "J3 regulated 5 V in, F1 polyfuse, Q3 reverse-polarity\nP-MOSFET with R1 and D2, D1 TVS on +5V."),
    ("Pi header", "pi_header.kicad_sch", "A3", pi_header.draw, (g(100), g(52)),
     "J1 Pi header, bottom side. R10, R11 I2C pull-ups and\nU2 ID EEPROM, not fitted. H1 to H8 holes."),
    ("Display and backlight", "display.kicad_sch", "A4", display.draw, (g(20), g(76)),
     "J2 socket for the DS1 ILI9341 module, R24, C1, C2,\nJP3. Q1, Q2 backlight switch on TFT_BL, R20 on."),
    ("Keys and dial", "inputs.kicad_sch", "A4", inputs.draw, (g(100), g(76)),
     "SW1 to SW6 keys, SW7 dial with push, R40 to R48,\nC40 to C48. J5 front panel header, not fitted."),
    ("Audio", "audio.kicad_sch", "A4", audio.draw, (g(20), g(100)),
     "AUDIO_PWM filter R30, C30, C31, R31, RV1 ceiling.\nM1 PAM8302A module, J6 speaker header, LS1."),
    ("Clock", "clock.kicad_sch", "A4", clock.draw, (g(100), g(100)),
     "U1 DS1338 at 0x68, Y1 crystal, BT1 CR1220 holder.\nJP1 VBAT jumper, R15 SQW pull-up, not fitted."),
    ("Serial and test points", "serial.kicad_sch", "A4", serial.draw, (g(20), g(124)),
     "J4 serial console, 3.3 V only.\nTP1 to TP5 on the rails and the I2C bus."),
    ("Holotape slot", "holotape.kicad_sch", "A3", holotape.draw, (g(100), g(124)),
     "J7 SD socket behind U4, U5 buffers on SPI0 CE1.\nU3 and Q4 switched card supply. TP9, TP10."),
]


# Sheets not drawn yet. While any is pending, the nets that J1 sends to them end
# on one pin, so ERC would flag their labels as isolated. The project then
# ignores that one rule. The last sheet empties this list and the rule is back.
PENDING = []


def build() -> Hierarchy:
    h = Hierarchy(PROJECT, board=BOARD, date="2026-11-23", rev="0.1",
                  comments=["Generated by pipboy-hat/gen/circuit.py. Do not edit by hand."])
    for name, file, paper, draw, at, notes in SHEETS:
        sheet = h.sheet(name, file, at, (g(56), g(14)), paper=paper, notes=notes)
        draw(sheet)
    root(h.root)
    return h


def root(s: Schematic) -> None:
    s.text("Pip-Boy HAT for the Raspberry Pi Zero, Zero W and Zero 2 W", (g(20), g(22)), size=2.5, bold=True)
    s.text("Proposal. Not built, not validated on hardware.\n"
           "J3 takes a REGULATED 5 V source only. No USB cable on the Pi while J3 is powered.\n"
           "Spec: pipboy-hat/spec/SPEC.md. Header map: spec/pins.yaml.\n"
           "Cross-sheet nets use global labels: I2C_SDA, I2C_SCL, ID_SD, ID_SC, SPI_SCLK, SPI_MOSI, SPI_MISO,\n"
           "TFT_CS, TFT_DC, TFT_RESET, TFT_BL, BTN_*, DIAL_A, DIAL_B, DIAL_PUSH, AUDIO_PWM, UART_TX, UART_RX,\n"
           "HOLO_CS, HOLO_CD, HOLO_WP. Rails use power symbols: +3V3, +5V, GND.", (g(20), g(42)))
    if PENDING:
        s.text("Not drawn yet: " + ", ".join(PENDING) + ".", (g(20), g(146)), size=2.0)


def main() -> None:
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "kicad")
    h = build()
    h.write(out)
    fps = set()
    for _, _, child in h.sheets:
        for node in child.symbols:
            for p in node:
                if isinstance(p, list) and len(p) > 2 and str(p[0]) == "property" and p[1] == "Footprint" and p[2]:
                    fps.add(p[2].split(":", 1)[0])
    write_project(out, PROJECT, h.stock_libs(), sorted(fps),
                  erc_severities={"isolated_pin_label": "ignore"} if PENDING else None)


if __name__ == "__main__":
    main()
