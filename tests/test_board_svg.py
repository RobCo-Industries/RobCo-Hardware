import xml.etree.ElementTree as ET

import pytest

from board_svg import BACKGROUND, normalise

RAW = """<?xml version="1.0" standalone="no"?>
<svg
  xmlns="http://www.w3.org/2000/svg"
  version="1.1"
  width="29.9974mm" height="19.9898mm" viewBox="0.0000 0.0000 29.9974 19.9898">
<title>SVG Image created as raw-top.svg date 2026-11-24T20:19:04 </title>
  <desc>Image generated by PCBNEW </desc>
<path d="M0 0 L30 0" />
</svg>
"""


def test_normalise_removes_the_date_and_adds_a_background():
    out = normalise(RAW, "toy board, top side")
    assert "2026" not in out and "<title>toy board, top side</title>" in out
    root = ET.fromstring(out.split("\n", 1)[1])
    ns = "{http://www.w3.org/2000/svg}"
    assert root.get("width") == "600" and root.get("height") is None
    first = [c for c in root if c.tag not in (ns + "title", ns + "desc")][0]
    assert first.tag == ns + "rect" and first.get("fill") == BACKGROUND
    assert first.get("width") == "29.9974"


def test_normalise_is_stable_across_export_dates():
    other = RAW.replace("2026-11-24T20:19:04", "2027-01-01T00:00:00").replace("raw-top", "x")
    assert normalise(RAW, "t") == normalise(other, "t")


def test_normalise_rejects_a_file_without_title():
    with pytest.raises(ValueError):
        normalise(RAW.replace("title", "nope"), "t")
